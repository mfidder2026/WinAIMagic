#!/usr/bin/env python3
"""Writes the generated half of docs/PARITY.md: each Swift test case and whether a test of the same name exists here.

    python scripts/parity.py <path to a MacAIMagic checkout>
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
mac = Path(sys.argv[1])
swift = {}
for f in sorted((mac / "App/Tests/MacAIMagicTests").glob("*.swift")):
    swift[f.name] = re.findall(r"func (test\w+)", f.read_text(encoding="utf-8"))

cs = {}
for f in (ROOT / "tests").rglob("*.cs"):
    if "\\obj\\" in str(f) or "\\bin\\" in str(f):
        continue
    for name in re.findall(r"(?:public|private|internal)?\s*(?:async\s+)?(?:void|Task)\s+(\w+)\s*\(", f.read_text(encoding="utf-8")):
        cs[name.lower().replace("_", "")] = f.parent.name


def norm(name):
    return re.sub(r"^test", "", name, flags=re.I).lower().replace("_", "")


lines = ["# Swift test cases and their counterparts", "",
         "Generated by `scripts/parity.py`. `Same name` is a test with the same name; `check by hand` means none has that name: "
         "it may be covered under another name, or be Mac-only.", "",
         "| Swift file | Test case | Status | Project |", "|---|---|---|---|"]
found = total = 0
for file, tests in swift.items():
    for t in tests:
        total += 1
        project = cs.get(norm(t))
        found += project is not None
        lines.append(f"| {file} | {t} | {'Same name' if project else 'check by hand'} | {project or ''} |")
lines[3:3] = [f"**{found} of {total}** have a test of the same name.", ""]
(ROOT / "docs" / "PARITY-tests.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(found, "of", total)
